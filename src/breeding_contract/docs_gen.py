def _md(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def load_field_examples(root: Path, contract: dict) -> dict:
    """Require a curated, schema-valid value for every field; version identity stays automatic."""
    path = root / FIELD_EXAMPLES
    if not path.is_file():
        raise ContractError(f"missing {FIELD_EXAMPLES}")
    examples = load_yaml(path)
    if not isinstance(examples, dict):
        raise ContractError(f"{FIELD_EXAMPLES} must map field paths to example values")
    automatic = {"common.schema_name": contract["name"], "common.schema_version": contract["version"]}
    expected = {f["path"] for f in contract["fields"]} - automatic.keys()
    missing, extra = expected - examples.keys(), examples.keys() - expected
    if missing or extra:
        raise ContractError(f"{FIELD_EXAMPLES}: missing examples {sorted(missing)}; unknown or automatic fields {sorted(extra)}")
    examples.update(automatic)
    defs = item_defs(contract)
    for f in contract["fields"]:
        schema = {**field_schema(contract, f), "$defs": defs}
        errors = list(Draft202012Validator(schema).iter_errors(examples[f["path"]]))
        if errors:
            raise ContractError(f"{FIELD_EXAMPLES}: {f['path']}: {errors[0].message}")
    return examples


def load_field_classification(root: Path, contract: dict) -> dict:
    """Load the user's four multi-select documentation tags and require explicit coverage."""
    path = root / FIELD_CLASSIFICATION
    if not path.is_file():
        raise ContractError(f"missing {FIELD_CLASSIFICATION}")
    classification = load_yaml(path)
    if not isinstance(classification, dict) or classification.get("classification_format") != 1:
        raise ContractError(f"{FIELD_CLASSIFICATION}: expected classification_format: 1")
    tags, fields = classification.get("tags"), classification.get("fields")
    if not isinstance(tags, dict) or set(tags) != {"research_1", "research_2", "iteration", "general"}:
        raise ContractError(f"{FIELD_CLASSIFICATION}: expected the four functional categories")
    for code, spec in tags.items():
        if not isinstance(spec, dict) or not all(isinstance(spec.get(k), str) and spec[k].strip()
                                                for k in ("label_zh", "description_zh")):
            raise ContractError(f"{FIELD_CLASSIFICATION}: {code} needs a label and description")
    if not isinstance(fields, dict):
        raise ContractError(f"{FIELD_CLASSIFICATION}: fields must map paths to tag lists")
    expected = {f["path"] for f in contract["fields"]}
    missing, extra = expected - fields.keys(), fields.keys() - expected
    if missing or extra:
        raise ContractError(f"{FIELD_CLASSIFICATION}: missing fields {sorted(missing)}; unknown fields {sorted(extra)}")
    for field, selected in fields.items():
        if not isinstance(selected, list) or not selected or \
                any(not isinstance(tag, str) or tag not in tags for tag in selected) or len(selected) != len(set(selected)):
            raise ContractError(f"{FIELD_CLASSIFICATION}: {field} needs a nonempty list of distinct valid tags")
    return classification


def _classification_label(classification: dict, path: str) -> str:
    return "、".join(classification["tags"][tag]["label_zh"] for tag in classification["fields"][path])


